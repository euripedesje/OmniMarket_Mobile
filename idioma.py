import os

IDIOMA = "en"
MOEDA = "$"   # simbolo da moeda da loja; "($)" nos textos vira "(R$)", "(€)" etc.
IDIOMAS_DISPONIVEIS = {"en": "English", "pt": "Português"}


def definir_idioma(codigo):
    global IDIOMA
    IDIOMA = codigo if codigo in TRADUCOES or codigo == "en" else "en"
    _salvar_ultimo_idioma(IDIOMA)


def T(texto):
    """Traduz um texto da interface para o idioma atual e ajusta o simbolo da moeda."""
    if IDIOMA != "en":
        texto = TRADUCOES.get(IDIOMA, {}).get(texto, texto)
    if MOEDA != "$" and "$" in texto:
        texto = texto.replace("($)", f"({MOEDA})")
        if texto.endswith(": $"):
            texto = texto[:-1] + MOEDA
    return texto


def _arquivo_idioma():
    base = os.environ.get("APPDATA") or os.path.expanduser("~")
    pasta = os.path.join(base, "OmniMarketPOS")
    try:
        os.makedirs(pasta, exist_ok=True)
    except Exception:
        return None
    return os.path.join(pasta, "idioma.txt")


def _salvar_ultimo_idioma(codigo):
    arq = _arquivo_idioma()
    if not arq:
        return
    try:
        with open(arq, "w", encoding="utf-8") as f:
            f.write(codigo)
    except Exception:
        pass


def carregar_ultimo_idioma():
    """Usado na tela de login, antes de saber a loja."""
    global IDIOMA
    arq = _arquivo_idioma()
    try:
        with open(arq, "r", encoding="utf-8") as f:
            cod = f.read().strip()
        if cod in TRADUCOES or cod == "en":
            IDIOMA = cod
    except Exception:
        pass
    return IDIOMA


